async function main() {
    try {
        console.log('Follow these steps to create your bot:\n');
        console.log('1. Open Telegram and search for @BotFather');
        console.log('2. Send /newbot to BotFather');
        console.log('3. Choose a name (e.g., "HypnoTagger Bot")');
        console.log('4. Choose a username ending with "bot" (e.g., "hypnotagger_bot")');
        console.log('5. Copy the bot token BotFather gives you\n');

        const token = await askQuestion('Enter your main bot token: ');

        if (!token) {
            console.log('❌ Bot token is required');
            process.exit(1);
        }

        console.log('\n🕵️ Optional: KinkScout Bot Setup');
        console.log('If you have a second bot for KinkScout character generation, enter its token.');
        console.log('Otherwise, just press Enter to skip.\n');

        const kinkscoutToken = await askQuestion('Enter KinkScout bot token (optional): ');

        console.log('\nNow add your bot to a chat/channel and send it a message (like /start)');
        await askQuestion('Press Enter when you\'ve sent a message to your bot...');

        const chatId = await getChatId(token);

        if (chatId) {
            await createEnvFile(token, chatId, kinkscoutToken);

            console.log('\n🚀 Your bot is ready! Next steps:');
            console.log('   1. Follow TELEGRAM-SETUP-GUIDE.md to create channels');
            console.log('   2. Use SETUP-CHECKLIST.md to track progress');
            console.log('   3. Run: node get-channel-ids.js');
            console.log('   4. Launch: ./start-hub.sh');
            console.log('\n💡 Test your bot with: /submit <video_url>');
            if (kinkscoutToken) {
                console.log('🕵️ KinkScout commands: /generate and /kinkscout');
            }
        } else {
            console.log('\n❌ Could not determine chat ID. Please check the steps above.');
        }
    } catch (error) {
        console.log('❌ Setup failed:', error.message);
    } finally {
        rl.close();
    }
}

main();
