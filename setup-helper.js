#!/usr/bin/env node

/**
 * 🎭 HypnoTagger Bot Setup Helper
 * Helps you configure your bot after creating it with BotFather
 */

const https = require('https');
const readline = require('readline');

const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout
});

console.log('🎭 HypnoTagger Bot Setup Helper\n');

async function askQuestion(question) {
    return new Promise((resolve) => {
        rl.question(question, (answer) => {
            resolve(answer.trim());
        });
    });
}

async function makeRequest(url) {
    return new Promise((resolve, reject) => {
        https.get(url, (res) => {
            let data = '';
            res.on('data', (chunk) => {
                data += chunk;
            });
            res.on('end', () => {
                try {
                    resolve(JSON.parse(data));
                } catch (parseError) {
                    reject(new Error(`Failed to parse JSON: ${parseError.message}`));
                }
            });
        }).on('error', (httpError) => {
            reject(new Error(`HTTP request failed: ${httpError.message}`));
        });
    });
}

async function getChatId(token) {
    try {
        console.log('\n🔍 Fetching recent updates...');
        const url = `https://api.telegram.org/bot${token}/getUpdates`;
        const response = await makeRequest(url);

        if (!response.ok) {
            console.log('❌ Error:', response.description);
            return null;
        }

        if (response.result.length === 0) {
            console.log('⚠️  No messages found. Please:');
            console.log('   1. Send a message to your bot (like /start)');
            console.log('   2. Run this script again');
            return null;
        }

        console.log('\n📋 Available chats:');
        const chats = new Map();

        response.result.forEach((update, index) => {
            if (update.message) {
                const chat = update.message.chat;
                const key = `${chat.type}_${chat.id}`;
                if (!chats.has(key)) {
                    chats.set(key, chat);
                    console.log(`   ${index + 1}. ${chat.type}: ${chat.title || chat.first_name || 'Unknown'} (ID: ${chat.id})`);
                }
            }
        });

        if (chats.size === 1) {
            const chat = Array.from(chats.values())[0];
            console.log(`\n✅ Using chat: ${chat.title || chat.first_name || 'Unknown'} (ID: ${chat.id})`);
            return chat.id;
        }

        const choice = await askQuestion('\nEnter the number of the chat to use: ');
        const chatArray = Array.from(chats.values());
        const selectedChat = chatArray[parseInt(choice) - 1];

        if (selectedChat) {
            return selectedChat.id;
        } else {
            console.log('❌ Invalid choice');
            return null;
        }
    } catch (error) {
        console.log('❌ Error fetching updates:', error.message);
        return null;
    }
}

